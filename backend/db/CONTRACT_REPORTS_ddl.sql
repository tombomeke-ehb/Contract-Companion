-- CONTRACT_REPORTS table: stores full analysis/report for each contract
CREATE TABLE CONTRACT_REPORTS (
    ID_REPORT NUMBER GENERATED AS IDENTITY NOT NULL,
    REPORT_JSON CLOB NOT NULL, -- Full analysis/report as JSON
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(ID_REPORT)
);

COMMENT ON TABLE CONTRACT_REPORTS IS 'Stores full analysis/report for contracts';
COMMENT ON COLUMN CONTRACT_REPORTS.REPORT_JSON IS 'Full analysis/report as JSON';
COMMENT ON COLUMN CONTRACT_REPORTS.CREATED_AT IS 'Creation timestamp';
COMMENT ON COLUMN CONTRACT_REPORTS.UPDATED_AT IS 'Last update timestamp';
