-- SQLite Schema for Contract Companion

-- Users table
CREATE TABLE IF NOT EXISTS USERS (
    ID_USER INTEGER PRIMARY KEY AUTOINCREMENT,
    NAME TEXT NOT NULL,
    SURNAME TEXT NOT NULL,
    EMAIL TEXT UNIQUE NOT NULL,
    PASSWORD TEXT NOT NULL,
    ISADMIN INTEGER DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Documents/Contracts table
CREATE TABLE IF NOT EXISTS DOCUMENTEN (
    ID_DOC INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_USER INTEGER NOT NULL,
    FILE_NAME TEXT NOT NULL,
    FILE_PATH TEXT NOT NULL,
    FILE_SIZE INTEGER,
    FILE_TYPE TEXT,
    TITLE TEXT,
    DESCRIPTION TEXT,
    RISK_SCORE REAL,
    RISK_LEVEL TEXT,
    STATUS TEXT DEFAULT 'pending',
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_USER) REFERENCES USERS(ID_USER) ON DELETE CASCADE
);

-- Contract Reports table
CREATE TABLE IF NOT EXISTS CONTRACT_REPORTS (
    ID_REPORT INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_DOC INTEGER,
    REPORT_JSON TEXT,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_DOC) REFERENCES DOCUMENTEN(ID_DOC) ON DELETE CASCADE
);

-- Summary/Analysis table
CREATE TABLE IF NOT EXISTS SAMENVATTING (
    ID_SUMMARY INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_DOC INTEGER NOT NULL,
    SUMMARY TEXT,
    RISK_SCORE REAL,
    KEY_CLAUSES TEXT,
    RED_FLAGS TEXT,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_DOC) REFERENCES DOCUMENTEN(ID_DOC) ON DELETE CASCADE
);

-- Calendar/Important dates table
CREATE TABLE IF NOT EXISTS KALENDER (
    ID_KALENDER INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_DOC INTEGER NOT NULL,
    EVENT_DATE DATE NOT NULL,
    EVENT_TYPE TEXT,
    DESCRIPTION TEXT,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_DOC) REFERENCES DOCUMENTEN(ID_DOC) ON DELETE CASCADE
);

-- End dates/Expiry table
CREATE TABLE IF NOT EXISTS EINDDATUM (
    ID_EINDDATUM INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_DOC INTEGER NOT NULL,
    END_DATE DATE,
    RENEWAL_TYPE TEXT,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_DOC) REFERENCES DOCUMENTEN(ID_DOC) ON DELETE CASCADE
);

-- Preferences table
CREATE TABLE IF NOT EXISTS PREFERENCES (
    PREF_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_USER INTEGER NOT NULL UNIQUE,
    THEME TEXT DEFAULT 'light',
    LANG TEXT DEFAULT 'nl',
    REGION TEXT DEFAULT 'BE',
    SESSION_TIMEOUT INTEGER DEFAULT 30,
    EXPIRY_REMINDER_DAYS INTEGER DEFAULT 7,
    AUTO_DELETE_DAYS INTEGER DEFAULT 30,
    RISK_ALERTS INTEGER DEFAULT 1,
    RISK_ALERTS_EMAIL INTEGER DEFAULT 1,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ID_USER) REFERENCES USERS(ID_USER) ON DELETE CASCADE
);

-- Notifications table
CREATE TABLE IF NOT EXISTS NOTIFICATIONS (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USER_ID INTEGER NOT NULL,
    TITLE TEXT,
    MESSAGE TEXT,
    CONTRACT_ID INTEGER,
    VARIANT TEXT,
    IS_READ INTEGER DEFAULT 0,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID_USER) ON DELETE CASCADE
);

-- Common Contracts Library table
CREATE TABLE IF NOT EXISTS COMMON_CONTRACTS (
    ID_CONTRACT INTEGER PRIMARY KEY AUTOINCREMENT,
    CONTRACT_KEY TEXT UNIQUE NOT NULL,
    NAME TEXT NOT NULL,
    CATEGORY TEXT NOT NULL,
    SUMMARY TEXT,
    RISK_HIGH INTEGER DEFAULT 0,
    RISK_MEDIUM INTEGER DEFAULT 0,
    RISK_LOW INTEGER DEFAULT 0,
    UPDATED_TEXT TEXT,
    SAMPLE_REPORT_ID INTEGER,
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CHK_CATEGORY CHECK (CATEGORY IN ('Subscriptions', 'Legal', 'Housing', 'Employment', 'Other'))
);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS IDX_DOCUMENTEN_USER ON DOCUMENTEN(ID_USER);
CREATE INDEX IF NOT EXISTS IDX_REPORTS_DOC ON CONTRACT_REPORTS(ID_DOC);
CREATE INDEX IF NOT EXISTS IDX_SAMENVATTING_DOC ON SAMENVATTING(ID_DOC);
CREATE INDEX IF NOT EXISTS IDX_KALENDER_DOC ON KALENDER(ID_DOC);
CREATE INDEX IF NOT EXISTS IDX_EINDDATUM_DOC ON EINDDATUM(ID_DOC);
CREATE INDEX IF NOT EXISTS IDX_COMMON_KEY ON COMMON_CONTRACTS(CONTRACT_KEY);
CREATE INDEX IF NOT EXISTS IDX_COMMON_CATEGORY ON COMMON_CONTRACTS(CATEGORY);
CREATE INDEX IF NOT EXISTS IDX_USERS_EMAIL ON USERS(EMAIL);

